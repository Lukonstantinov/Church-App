type Widen<T> = T extends string
  ? string
  : T extends readonly string[]
    ? string[]
    : T extends (...args: infer A) => infer R
      ? (...args: A) => Widen<R>
      : { [K in keyof T]: Widen<T[K]> };

/** The shape every language must implement. */
export type Messages = Widen<typeof ru>;
